create table if not exists public.marketing_visit_events (
  id bigint generated by default as identity primary key,
  visitor_id uuid not null references public.marketing_visitors(visitor_id) on delete cascade,
  landing_path text,
  referrer text,
  first_utm_source text,
  first_utm_medium text,
  first_utm_campaign text,
  first_utm_term text,
  first_utm_content text,
  first_gclid text,
  first_fbclid text,
  first_msclkid text,
  last_utm_source text,
  last_utm_medium text,
  last_utm_campaign text,
  last_utm_term text,
  last_utm_content text,
  last_gclid text,
  last_fbclid text,
  last_msclkid text,
  seen_at timestamptz not null default now(),
  created_at timestamptz not null default now()
);

create index if not exists idx_marketing_visit_events_seen_at
  on public.marketing_visit_events (seen_at desc);

create index if not exists idx_marketing_visit_events_visitor_id
  on public.marketing_visit_events (visitor_id);

create index if not exists idx_marketing_visit_events_first_source
  on public.marketing_visit_events (first_utm_source, first_utm_medium, first_utm_campaign);

alter table public.marketing_visit_events enable row level security;

drop policy if exists marketing_visit_events_deny_all on public.marketing_visit_events;
create policy marketing_visit_events_deny_all
  on public.marketing_visit_events
  for all
  using (false)
  with check (false);

revoke all on table public.marketing_visit_events from anon, authenticated;

create or replace function public.record_marketing_visit(
  p_visitor_id uuid,
  p_landing_path text,
  p_referrer text,
  p_first_utm_source text,
  p_first_utm_medium text,
  p_first_utm_campaign text,
  p_first_utm_term text,
  p_first_utm_content text,
  p_first_gclid text,
  p_first_fbclid text,
  p_first_msclkid text,
  p_last_utm_source text,
  p_last_utm_medium text,
  p_last_utm_campaign text,
  p_last_utm_term text,
  p_last_utm_content text,
  p_last_gclid text,
  p_last_fbclid text,
  p_last_msclkid text,
  p_seen_at timestamptz default now()
)
returns void
language plpgsql
set search_path = public
as $$
declare
  v_seen_at timestamptz := coalesce(p_seen_at, now());
  v_landing_path text := nullif(left(coalesce(p_landing_path, ''), 500), '');
  v_referrer text := nullif(left(coalesce(p_referrer, ''), 500), '');
  v_first_utm_source text := nullif(left(coalesce(p_first_utm_source, ''), 200), '');
  v_first_utm_medium text := nullif(left(coalesce(p_first_utm_medium, ''), 200), '');
  v_first_utm_campaign text := nullif(left(coalesce(p_first_utm_campaign, ''), 200), '');
  v_first_utm_term text := nullif(left(coalesce(p_first_utm_term, ''), 200), '');
  v_first_utm_content text := nullif(left(coalesce(p_first_utm_content, ''), 200), '');
  v_first_gclid text := nullif(left(coalesce(p_first_gclid, ''), 200), '');
  v_first_fbclid text := nullif(left(coalesce(p_first_fbclid, ''), 200), '');
  v_first_msclkid text := nullif(left(coalesce(p_first_msclkid, ''), 200), '');
  v_last_utm_source text := nullif(left(coalesce(p_last_utm_source, ''), 200), '');
  v_last_utm_medium text := nullif(left(coalesce(p_last_utm_medium, ''), 200), '');
  v_last_utm_campaign text := nullif(left(coalesce(p_last_utm_campaign, ''), 200), '');
  v_last_utm_term text := nullif(left(coalesce(p_last_utm_term, ''), 200), '');
  v_last_utm_content text := nullif(left(coalesce(p_last_utm_content, ''), 200), '');
  v_last_gclid text := nullif(left(coalesce(p_last_gclid, ''), 200), '');
  v_last_fbclid text := nullif(left(coalesce(p_last_fbclid, ''), 200), '');
  v_last_msclkid text := nullif(left(coalesce(p_last_msclkid, ''), 200), '');
begin
  insert into public.marketing_visitors (
    visitor_id,
    landing_path,
    referrer,
    first_utm_source,
    first_utm_medium,
    first_utm_campaign,
    first_utm_term,
    first_utm_content,
    first_gclid,
    first_fbclid,
    first_msclkid,
    last_utm_source,
    last_utm_medium,
    last_utm_campaign,
    last_utm_term,
    last_utm_content,
    last_gclid,
    last_fbclid,
    last_msclkid,
    first_seen_at,
    last_seen_at
  )
  values (
    p_visitor_id,
    v_landing_path,
    v_referrer,
    v_first_utm_source,
    v_first_utm_medium,
    v_first_utm_campaign,
    v_first_utm_term,
    v_first_utm_content,
    v_first_gclid,
    v_first_fbclid,
    v_first_msclkid,
    v_last_utm_source,
    v_last_utm_medium,
    v_last_utm_campaign,
    v_last_utm_term,
    v_last_utm_content,
    v_last_gclid,
    v_last_fbclid,
    v_last_msclkid,
    v_seen_at,
    v_seen_at
  )
  on conflict (visitor_id) do update set
    last_utm_source = excluded.last_utm_source,
    last_utm_medium = excluded.last_utm_medium,
    last_utm_campaign = excluded.last_utm_campaign,
    last_utm_term = excluded.last_utm_term,
    last_utm_content = excluded.last_utm_content,
    last_gclid = excluded.last_gclid,
    last_fbclid = excluded.last_fbclid,
    last_msclkid = excluded.last_msclkid,
    last_seen_at = excluded.last_seen_at,
    visit_count = public.marketing_visitors.visit_count + 1,
    updated_at = now();

  insert into public.marketing_visit_events (
    visitor_id,
    landing_path,
    referrer,
    first_utm_source,
    first_utm_medium,
    first_utm_campaign,
    first_utm_term,
    first_utm_content,
    first_gclid,
    first_fbclid,
    first_msclkid,
    last_utm_source,
    last_utm_medium,
    last_utm_campaign,
    last_utm_term,
    last_utm_content,
    last_gclid,
    last_fbclid,
    last_msclkid,
    seen_at
  )
  values (
    p_visitor_id,
    v_landing_path,
    v_referrer,
    v_first_utm_source,
    v_first_utm_medium,
    v_first_utm_campaign,
    v_first_utm_term,
    v_first_utm_content,
    v_first_gclid,
    v_first_fbclid,
    v_first_msclkid,
    v_last_utm_source,
    v_last_utm_medium,
    v_last_utm_campaign,
    v_last_utm_term,
    v_last_utm_content,
    v_last_gclid,
    v_last_fbclid,
    v_last_msclkid,
    v_seen_at
  );
end;
$$;

