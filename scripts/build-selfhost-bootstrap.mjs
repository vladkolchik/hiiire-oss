import { readFile, writeFile } from "node:fs/promises";
import { resolve } from "node:path";

const root = process.cwd();
const manifestPath = resolve(root, "supabase/bootstrap/selfhost_manifest.txt");
const basePath = resolve(root, "supabase/bootstrap/selfhost_base.sql");
const finalPath = resolve(root, "supabase/bootstrap/selfhost_final.sql");
const outputPath = resolve(
  root,
  "supabase/migrations/20260701125302_selfhost_bootstrap.sql",
);

const manifest = (await readFile(manifestPath, "utf8"))
  .split(/\r?\n/)
  .map((line) => line.trim())
  .filter((line) => line && !line.startsWith("#"));

const missing = [];
const sections = [
  "-- Generated by scripts/build-selfhost-bootstrap.mjs.",
  "-- Do not edit this file directly; edit the baseline or source SQL files.",
  "",
  await readFile(basePath, "utf8"),
];

for (const relativePath of manifest) {
  let sql;
  try {
    sql = await readFile(resolve(root, relativePath), "utf8");
  } catch {
    missing.push(relativePath);
    continue;
  }

  // The final bootstrap is one transaction when applied by Supabase MCP.
  // Strip file-local transaction wrappers and avoid CONCURRENTLY, which is
  // illegal inside a migration transaction.
  sql = sql
    .replace(/^\s*(begin|commit|rollback)\s*;\s*$/gim, "")
    .replace(/\bcreate\s+index\s+concurrently\b/gi, "create index");

  sections.push(
    "",
    `-- ------------------------------------------------------------------`,
    `-- Source: ${relativePath}`,
    `-- ------------------------------------------------------------------`,
    sql.trim(),
    "",
  );
}

if (missing.length > 0) {
  throw new Error(`Missing bootstrap sources:\n${missing.join("\n")}`);
}

sections.push(
  "",
  "-- ------------------------------------------------------------------",
  "-- Final recovery overlay",
  "-- ------------------------------------------------------------------",
  await readFile(finalPath, "utf8"),
);

await writeFile(outputPath, `${sections.join("\n").trim()}\n`, "utf8");
console.log(`Generated ${outputPath} from ${manifest.length} SQL files.`);
